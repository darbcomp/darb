const normalize = (value = "") => String(value).replace(/\s+/g, " ").trim();

export function translateToArabic(value = "") {
  const raw = String(value);
  const normalized = normalize(raw);
  if (!normalized) return raw;

  const exact = ARABIC_TEXT[normalized];
  if (exact) {
    const leading = raw.match(/^\s*/)?.[0] || "";
    const trailing = raw.match(/\s*$/)?.[0] || "";
    return `${leading}${exact}${trailing}`;
  }

  for (const [pattern, render] of ARABIC_PATTERNS) {
    const match = normalized.match(pattern);
    if (match) {
      const leading = raw.match(/^\s*/)?.[0] || "";
      const trailing = raw.match(/\s*$/)?.[0] || "";
      return `${leading}${render(match)}${trailing}`;
    }
  }

  return raw;
}

export function translateLabel(value, language) {
  return language === "ar" ? translateToArabic(value) : value;
}
